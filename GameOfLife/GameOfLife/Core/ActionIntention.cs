namespace GameOfLife.Core
{
    /// <summary>
    /// Тип намерения действия бота.
    /// 
    /// Определяет какие действия бот может заявить как намерение
    /// перед фактическим выполнением. Это позволяет движку собрать
    /// все намерения и разрешить конфликты до выполнения.
    /// </summary>
    public enum IntentionType
    {
        /// <summary>
        /// Бот намерен переместиться в целевую клетку.
        /// Требует: целевая клетка свободна, достаточно энергии.
        /// </summary>
        Move,

        /// <summary>
        /// Бот намерен остаться на текущей клетке.
        /// Не создаёт конфликтов с другими ботами.
        /// </summary>
        Stay,

        /// <summary>
        /// Бот намерен атаковать бота в целевой клетке.
        /// Требует: наличие цели в целевой клетке, достаточно энергии.
        /// </summary>
        Attack,

        /// <summary>
        /// Бот намерен собрать ресурсы в текущей клетке.
        /// Не создаёт конфликтов если ресурсы общие.
        /// </summary>
        Gather,

        /// <summary>
        /// Бот намерен построить структуру в текущей клетке.
        /// Требует: клетка свободна, есть строительные материалы.
        /// </summary>
        Build,

        /// <summary>
        /// Бот намерен отдохнуть для восстановления энергии.
        /// Не создаёт конфликтов с другими ботами.
        /// </summary>
        Rest
    }

    /// <summary>
    /// Намерение действия бота для следующего тика симуляции.
    /// 
    /// Этот класс инкапсулирует желание бота выполнить действие
    /// без фактического выполнения. Движок собирает все намерения,
    /// разрешает конфликты между ними, и только затем выполняет
    /// разрешённые действия.
    /// 
    /// Архитектурные преимущества:
    /// - Изотропность: порядок обработки ботов не влияет на результат
    /// - Детерминизм: одинаковые входные данные = одинаковый результат
    /// - Разрешение конфликтов: центральная логика вместо распределённой
    /// - Откат действий: неудачные намерения не меняют состояние мира
    /// 
    /// Жизненный цикл намерения:
    /// 1. Создание: Bot.CreateIntention() создаёт намерение
    /// 2. Сбор: SimulationEngine собирает все намерения ботов
    /// 3. Разрешение: ConflictResolver разрешает конфликты
    /// 4. Выполнение: разрешённые намерения выполняются
    /// 5. Отбрасывание: запрещённые намерения игнорируются
    /// </summary>
    public class ActionIntention
    {
        #region Приватные поля

        /// <summary>
        /// Бот который создал это намерение.
        /// 
        /// Используется для:
        /// - Определения приоритета при конфликте
        /// - Выполнения разрешённого действия
        /// - Логирования и отладки
        /// </summary>
        private readonly Entities.Bot _bot;

        #endregion

        #region Публичные свойства

        /// <summary>
        /// Бот который создал это намерение.
        /// 
        /// Только для чтения. Устанавливается в конструкторе
        /// и не может быть изменён после создания.
        /// </summary>
        public Entities.Bot Bot => _bot;

        /// <summary>
        /// Тип намеренного действия.
        /// 
        /// Определяет как намерение будет обработано системой
        /// разрешения конфликтов. Разные типы имеют разные
        /// правила приоритета и разрешения конфликтов.
        /// </summary>
        public IntentionType Type { get; set; }

        /// <summary>
        /// Целевая координата X для действия.
        /// 
        /// Для Move/Attack: клетка куда бот хочет переместиться/атаковать
        /// Для Stay/Gather/Rest: текущая координата бота
        /// Для Build: клетка где бот хочет построить структуру
        /// </summary>
        public int TargetX { get; set; }

        /// <summary>
        /// Целевая координата Y для действия.
        /// 
        /// Для Move/Attack: клетка куда бот хочет переместиться/атаковать
        /// Для Stay/Gather/Rest: текущая координата бота
        /// Для Build: клетка где бот хочет построить структуру
        /// </summary>
        public int TargetY { get; set; }

        /// <summary>
        /// Приоритет намерения.
        /// 
        /// Используется системой разрешения конфликтов для определения
        /// какой бот получит преимущество при конкуренции за клетку.
        /// 
        /// Факторы влияющие на приоритет:
        /// - Текущая энергия бота (больше энергии = выше приоритет)
        /// - Срочность действия (бегство > атака > движение > отдых)
        /// - Случайный фактор для избежания предсказуемости
        /// 
        /// Диапазон: 0 (минимальный) до 1000 (максимальный)
        /// </summary>
        public float Priority { get; set; }

        /// <summary>
        /// Флаг разрешения намерения.
        /// 
        /// true: намерение прошло разрешение конфликтов и будет выполнено
        /// false: намерение заблокировано и будет проигнорировано
        /// 
        /// Устанавливается ConflictResolver после анализа всех намерений.
        /// До этого момента значение не определено.
        /// </summary>
        public bool IsResolved { get; set; }

        /// <summary>
        /// Флаг успешности намерения.
        /// 
        /// true: намерение было разрешено И успешно выполнено
        /// false: намерение было заблокировано ИЛИ выполнение провалилось
        /// 
        /// Отличается от IsResolved тем что учитывает ошибки выполнения:
        /// - IsResolved = true, IsSuccessful = false: разрешено но не вышло
        /// - IsResolved = false, IsSuccessful = false: заблокировано
        /// </summary>
        public bool IsSuccessful { get; set; }

        #endregion

        #region Конструктор

        /// <summary>
        /// Создаёт новое намерение действия для бота.
        /// 
        /// Инициализирует намерение с параметрами по умолчанию:
        /// - IsResolved = false (ожидает разрешения)
        /// - IsSuccessful = false (ещё не выполнено)
        /// - Priority = рассчитывается на основе энергии бота
        /// 
        /// Важно: намерение не выполняет действие при создании.
        /// Оно только декларирует желание бота выполнить действие.
        /// </summary>
        /// <param name="bot">Бот который создаёт намерение.</param>
        public ActionIntention(Entities.Bot bot)
        {
            _bot = bot ?? throw new System.ArgumentNullException(nameof(bot));
            IsResolved = false;
            IsSuccessful = false;

            // Базовый приоритет на основе энергии бота
            // Боты с большей энергией имеют преимущество
            Priority = bot.Energy;
        }

        /// <summary>
        /// Создаёт новое намерение с полным набором параметров.
        /// 
        /// Используется когда нужно явно указать все параметры
        /// вместо расчёта по умолчанию.
        /// </summary>
        /// <param name="bot">Бот который создаёт намерение.</param>
        /// <param name="type">Тип намеренного действия.</param>
        /// <param name="targetX">Целевая координата X.</param>
        /// <param name="targetY">Целевая координата Y.</param>
        /// <param name="priority">Приоритет намерения.</param>
        public ActionIntention(
            Entities.Bot bot,
            IntentionType type,
            int targetX,
            int targetY,
            float priority)
        {
            _bot = bot ?? throw new System.ArgumentNullException(nameof(bot));
            Type = type;
            TargetX = targetX;
            TargetY = targetY;
            Priority = priority;
            IsResolved = false;
            IsSuccessful = false;
        }

        #endregion

        #region Вспомогательные методы

        /// <summary>
        /// Проверяет требует ли намерение целевую клетку.
        /// 
        /// Намерения типа Move и Attack требуют эксклюзивного
        /// доступа к целевой клетке. Если другой бот тоже хочет
        /// эту клетку — возникает конфликт.
        /// 
        /// Намерения типа Stay и Rest не требуют эксклюзивного
        /// доступа и не создают конфликтов.
        /// </summary>
        /// <returns>True если намерение требует целевую клетку.</returns>
        public bool RequiresTargetCell()
        {
            return Type == IntentionType.Move ||
                   Type == IntentionType.Attack ||
                   Type == IntentionType.Build;
        }

        /// <summary>
        /// Проверяет является ли намерение конфликтным.
        /// 
        /// Конфликтные намерения — те которые могут конкурировать
        /// с намерениями других ботов за один ресурс (клетку).
        /// 
        /// Не конфликтные намерения могут выполняться параллельно
        /// без необходимости разрешения конфликтов.
        /// </summary>
        /// <returns>True если намерение может создать конфликт.</returns>
        public bool IsConflicting()
        {
            return RequiresTargetCell();
        }

        /// <summary>
        /// Возвращает строковое представление намерения для отладки.
        /// 
        /// Формат: "Type(TargetX, TargetY) Priority [Resolved/Successful]"
        /// Пример: "Move(50, 50) 150.5 [R:S]"
        /// </summary>
        /// <returns>Строка для отладки.</returns>
        public override string ToString()
        {
            string status = IsResolved ? (IsSuccessful ? "R+S+" : "R+S-") : "R-S-";
            return $"{Type}({TargetX}, {TargetY}) {Priority:F1} [{status}]";
        }

        #endregion
    }
}