using System;

namespace GameOfLife.Data
{
    /// <summary>
    /// Интерфейс для систем сохранения и загрузки.
    /// 
    /// Определяет контракт для всех реализаций систем сохранения.
    /// Позволяет подменять форматы сохранения без изменения кода движка.
    /// 
    /// Реализации:
    /// - JsonSaveLoad: сохранение в JSON (читаемый формат)
    /// - BinarySaveLoad: сохранение в бинарном формате (компактный)
    /// - XmlSaveLoad: сохранение в XML (устаревший, для совместимости)
    /// 
    /// Преимущества интерфейса:
    /// - Возможность добавления новых форматов без изменения ядра
    /// - Легкое тестирование с моковыми реализациями
    /// - Поддержка стратегии выбора формата сохранения
    /// </summary>
    public interface ISaveLoad
    {
        /// <summary>
        /// Сохраняет состояние симуляции в файл.
        /// 
        /// Метод сериализует все необходимые данные:
        /// - Состояние мира (клетки)
        /// - Параметры конфигурации
        /// - Состояние ботов (для режима экосистемы)
        /// - Параметры окружающей среды
        /// - Статистику симуляции
        /// 
        /// Метод должен быть асинхронным для больших сохранений.
        /// </summary>
        /// <param name="saveData">Данные для сохранения.</param>
        /// <param name="filePath">Путь к файлу сохранения.</param>
        /// <returns>True если сохранение успешно, иначе false.</returns>
        bool Save(SaveGame saveData, string filePath);

        /// <summary>
        /// Загружает состояние симуляции из файла.
        /// 
        /// Метод десериализует данные из файла и восстанавливает:
        /// - Состояние мира (клетки)
        /// - Параметры конфигурации
        /// - Состояние ботов (для режима экосистемы)
        /// - Параметры окружающей среды
        /// - Статистику симуляции
        /// 
        /// Метод должен проверять версию формата для совместимости.
        /// </summary>
        /// <param name="filePath">Путь к файлу сохранения.</param>
        /// <returns>Загруженные данные или null если ошибка.</returns>
        SaveGame Load(string filePath);

        /// <summary>
        /// Проверяет существование файла сохранения.
        /// </summary>
        /// <param name="filePath">Путь к файлу.</param>
        /// <returns>True если файл существует, иначе false.</returns>
        bool Exists(string filePath);

        /// <summary>
        /// Удаляет файл сохранения.
        /// </summary>
        /// <param name="filePath">Путь к файлу.</param>
        /// <returns>True если удаление успешно, иначе false.</returns>
        bool Delete(string filePath);

        /// <summary>
        /// Получает информацию о файле сохранения.
        /// </summary>
        /// <param name="filePath">Путь к файлу.</param>
        /// <returns>Информация о сохранении или null.</returns>
        SaveInfo GetSaveInfo(string filePath);
    }
}