using GameOfLife.Core;

namespace GameOfLife.Entities
{
    /// <summary>
    /// Общий интерфейс для всех сущностей, находящихся в мире.
    /// 
    /// Этот интерфейс позволяет обрабатывать разные типы объектов
    /// (боты, структуры, ресурсы) единообразно в системах мира.
    /// 
    /// Преимущества использования интерфейса:
    /// - Единый способ получения координат для всех сущностей
    /// - Возможность хранения разнородных объектов в общих коллекциях
    /// - Упрощение системы коллизий и поиска соседей
    /// - Поддержка полиморфизма при обработке сущностей
    /// </summary>
    public interface IEntity
    {
        /// <summary>
        /// Уникальный идентификатор сущности.
        /// 
        /// Используется для:
        /// - Отслеживания сущности в течение жизни симуляции
        /// - Разрешения конфликтов при взаимодействии
        /// - Логирования и отладки
        /// - Сериализации при сохранении состояния
        /// 
        /// Значение должно быть уникальным в пределах одной симуляции.
        /// Рекомендуется использовать Guid или последовательный числовой ID.
        /// </summary>
        int Id { get; }

        /// <summary>
        /// Горизонтальная координата сущности в мире.
        /// 
        /// Координата измеряется в клетках мира (не в пикселях).
        /// Значение должно находиться в диапазоне [0, WorldWidth).
        /// 
        /// При перемещении сущности это свойство должно обновляться.
        /// Изменение координаты не должно происходить напрямую извне —
        /// используйте методы перемещения, предоставляемые движком.
        /// </summary>
        int X { get; }

        /// <summary>
        /// Вертикальная координата сущности в мире.
        /// 
        /// Координата измеряется в клетках мира (не в пикселях).
        /// Значение должно находиться в диапазоне [0, WorldHeight).
        /// 
        /// При перемещении сущности это свойство должно обновляться.
        /// Изменение координаты не должно происходить напрямую извне —
        /// используйте методы перемещения, предоставляемые движком.
        /// </summary>
        int Y { get; }

        /// <summary>
        /// Индикатор активности сущности.
        /// 
        /// true: сущность активна и участвует в симуляции
        /// false: сущность неактивна и должна быть удалена из мира
        /// 
        /// Это свойство используется движком для:
        /// - Фильтрации неактивных сущностей при обновлении
        /// - Оптимизации поиска и обработки
        /// - Корректного удаления "мёртвых" объектов
        /// 
        /// После установки в false сущность больше не должна
        /// изменять своё состояние или взаимодействовать с миром.
        /// </summary>
        bool IsActive { get; }

        /// <summary>
        /// Выполняет один шаг логики сущности.
        /// 
        /// Этот метод вызывается движком каждый тик симуляции
        /// для всех активных сущностей. В нём должна содержаться
        /// вся логика поведения сущности:
        /// - Принятие решений на основе состояния мира
        /// - Взаимодействие с другими сущностями
        /// - Изменение собственного состояния
        /// - Запрос действий у движка (перемещение, атака и т.д.)
        /// 
        /// Важно: метод не должен напрямую модифицировать состояние мира.
        /// Все изменения должны происходить через запросы к SimulationEngine.
        /// Это обеспечивает детерминизм и корректную обработку конфликтов.
        /// </summary>
        /// <param name="engine">Ссылка на движок симуляции для запросов.</param>
        void Tick(SimulationEngine engine);
    }
}