using System;

namespace GameOfLife.Rendering
{
    /// <summary>
    /// Интерфейс рендерера.
    /// Определяет контракт для всех типов визуализации.
    /// 
    /// Этот интерфейс позволяет реализовать принцип инверсии зависимостей (DIP).
    /// Движок симуляции зависит от абстракции (IRenderer), а не от конкретных
    /// реализаций. Это даёт возможность:
    /// - Подменять рендереры без изменения ядра симуляции
    /// - Добавлять новые типы визуализации (консоль, веб, видео)
    /// - Отключать визуализацию полностью для headless режима
    /// - Тестировать симуляцию без зависимостей от UI
    /// 
    /// Реализации интерфейса:
    /// - WinFormsRenderer: отрисовка в PictureBox Windows Forms
    /// - BitmapRenderer: отрисовка в память (Bitmap) для экспорта
    /// - ConsoleRenderer: текстовая отрисовка в консоль
    /// - NullRenderer: отсутствие отрисовки (максимальная производительность)
    /// </summary>
    public interface IRenderer : IDisposable
    {
        /// <summary>
        /// Конфигурация рендерера.
        /// Содержит все настраиваемые параметры визуализации:
        /// - Размер клетки в пикселях
        /// - Цвета живой и мёртвой клетки
        /// - Параметры сетки
        /// - Дополнительные опции отображения
        /// 
        /// Может быть изменена во время выполнения для динамической
        /// настройки внешнего вида без пересоздания рендерера.
        /// </summary>
        RenderConfig Config { get; set; }

        /// <summary>
        /// Отрисовывает текущее состояние мира.
        /// Вызывается движком после каждого шага симуляции.
        /// 
        /// Этот метод должен быть потокобезопасным, так как может вызываться
        /// из фонового потока симуляции. Реализации должны самостоятельно
        /// обеспечивать синхронизацию при доступе к общим ресурсам.
        /// 
        /// Для UI-рендереров (WinForms) требуется маршалинг в UI поток.
        /// Для рендереров в память (Bitmap) допускается выполнение в любом потоке.
        /// </summary>
        /// <param name="worldState">
        /// Состояние мира для отрисовки. Содержит:
        /// - Двумерный массив клеток (WorldArray)
        /// - Номер текущего поколения (Generation)
        /// - Количество живых клеток (LiveCellCount)
        /// - Размеры мира (Width, Height)
        /// </param>
        void Render(Core.WorldState worldState);

        /// <summary>
        /// Сохраняет текущий кадр в файл.
        /// Используется для экспорта отдельных изображений (PNG, BMP).
        /// 
        /// Метод должен сохранять последнее отрисованное состояние.
        /// Если Render ещё не вызывался, поведение не определено.
        /// 
        /// Формат файла определяется по расширению в пути:
        /// - .png → PNG формат
        /// - .bmp → BMP формат
        /// - .jpg → JPEG формат
        /// </summary>
        /// <param name="filePath">
        /// Полный путь к файлу для сохранения.
        /// Директория должна существовать, иначе будет выброшено исключение.
        /// </param>
        void SaveFrame(string filePath);

        /// <summary>
        /// Начинает запись анимации (для GIF/видео).
        /// 
        /// После вызова этого метода все последующие кадры, переданные в Render,
        /// сохраняются во внутреннем буфере для последующего создания анимации.
        /// 
        /// Важно: запись кадров потребляет дополнительную память.
        /// Для длинных анимаций рекомендуется периодически вызывать EndRecording
        /// и начинать новую запись.
        /// 
        /// Если запись уже идёт, метод ничего не делает.
        /// </summary>
        void BeginRecording();

        /// <summary>
        /// Завершает запись анимации и сохраняет в файл.
        /// 
        /// Создаёт анимированный файл из всех кадров, накопленных
        /// между BeginRecording и EndRecording.
        /// 
        /// После вызова этого метода внутренний буфер кадров очищается.
        /// Для продолжения записи необходимо снова вызвать BeginRecording.
        /// 
        /// Поддерживаемые форматы:
        /// - .gif → Анимированный GIF (требует пакет AnimatedGif)
        /// - .avi → Видео AVI (требует дополнительные библиотеки)
        /// </summary>
        /// <param name="outputPath">
        /// Полный путь к выходному файлу.
        /// </param>
        /// <param name="fps">
        /// Количество кадров в секунду для анимации.
        /// Рекомендуемые значения: 10-30 FPS.
        /// Чем выше FPS, тем плавнее анимация, но больше размер файла.
        /// </param>
        void EndRecording(string outputPath, int fps);

        /// <summary>
        /// Событие завершения отрисовки кадра.
        /// 
        /// Вызывается после успешной отрисовки каждого кадра.
        /// Содержит статистику производительности рендеринга.
        /// 
        /// Подписчики могут использовать это событие для:
        /// - Отслеживания FPS рендеринга
        /// - Логирования производительности
        /// - Обновления UI с информацией о рендеринге
        /// - Принятия решений об оптимизации
        /// </summary>
        event Action<RenderStats> OnRenderCompleted;
    }

    /// <summary>
    /// Статистика отрисовки кадра.
    /// 
    /// Содержит метрики производительности и информацию о кадре.
    /// Используется для мониторинга и отладки системы рендеринга.
    /// 
    /// Все значения доступны только для чтения после создания объекта.
    /// </summary>
    public class RenderStats
    {
        /// <summary>
        /// Время отрисовки кадра в миллисекундах.
        /// 
        /// Включает время на:
        /// - Создание/очистку Bitmap
        /// - Отрисовку всех живых клеток
        /// - Отрисовку сетки (если включена)
        /// - Копирование в UI (для WinFormsRenderer)
        /// 
        /// Нормальные значения:
        /// - Менее 10 мс: отличная производительность
        /// - 10-50 мс: приемлемая производительность
        /// - Более 50 мс: возможны задержки визуализации
        /// </summary>
        public long RenderTimeMs { get; set; }

        /// <summary>
        /// Номер поколения, которое было отрисовано.
        /// 
        /// Используется для синхронизации статистики с состоянием симуляции.
        /// Позволяет отследить, какое поколение вызвало проблемы с производительностью.
        /// </summary>
        public long Generation { get; set; }

        /// <summary>
        /// Количество живых клеток в отрисованном кадре.
        /// 
        /// Влияет на время отрисовки: больше живых клеток = дольше рендеринг.
        /// Полезно для анализа корреляции между сложностью состояния и производительностью.
        /// </summary>
        public int LiveCellCount { get; set; }

        /// <summary>
        /// Ширина кадра в пикселях.
        /// Вычисляется как: WorldWidth * CellSize
        /// </summary>
        public int Width { get; set; }

        /// <summary>
        /// Высота кадра в пикселях.
        /// Вычисляется как: WorldHeight * CellSize
        /// </summary>
        public int Height { get; set; }

        /// <summary>
        /// Вычисляет примерный FPS рендеринга.
        /// </summary>
        /// <returns>Кадров в секунду (0 если RenderTimeMs = 0).</returns>
        public double GetFps()
        {
            if (RenderTimeMs <= 0)
                return 0;

            return 1000.0 / RenderTimeMs;
        }
    }

    /// <summary>
    /// Конфигурация рендерера.
    /// 
    /// Содержит все визуальные параметры для отрисовки мира.
    /// Может быть изменена во время выполнения для динамической
    /// настройки внешнего вида.
    /// 
    /// Все изменения конфигурации применяются к следующему кадру.
    /// </summary>
    public class RenderConfig
    {
        /// <summary>
        /// Размер клетки в пикселях (зум).
        /// 
        /// Влияет на:
        /// - Общий размер изображения
        /// - Детализацию отрисовки
        /// - Производительность рендеринга
        /// 
        /// Рекомендуемые значения:
        /// - 1-2 пикселя: для больших миров (headless экспорт)
        /// - 4-8 пикселей: для обычного просмотра
        /// - 16-64 пикселя: для детального просмотра малых областей
        /// </summary>
        public int CellSize { get; set; } = 4;

        /// <summary>
        /// Цвет живой клетки.
        /// 
        /// Используется для заполнения прямоугольников живых клеток.
        /// Может быть изменён для визуального различия типов клеток
        /// в будущих расширениях (экосистема с разными типами ботов).
        /// </summary>
        public System.Drawing.Color AliveColor { get; set; } = System.Drawing.Color.Crimson;

        /// <summary>
        /// Цвет мёртвой клетки (фона).
        /// 
        /// Используется для очистки всего изображения перед отрисовкой.
        /// Тёмные цвета рекомендуются для снижения нагрузки на глаза
        /// при длительном наблюдении за симуляцией.
        /// </summary>
        public System.Drawing.Color DeadColor { get; set; } = System.Drawing.Color.Black;

        /// <summary>
        /// Цвет сетки.
        /// 
        /// Используется для отрисовки линий между клетками.
        /// Должен контрастировать с DeadColor и AliveColor.
        /// Серые тона рекомендуются для нейтрального вида.
        /// </summary>
        public System.Drawing.Color GridColor { get; set; } = System.Drawing.Color.DarkGray;

        /// <summary>
        /// Толщина линии сетки в пикселях.
        /// 
        /// Значение 0 или 1: тонкая сетка (рекомендуется)
        /// Значение 2+: жирная сетка (для презентаций)
        /// 
        /// При CellSize = 1 сетка не имеет смысла и должна быть отключена.
        /// </summary>
        public int GridThickness { get; set; } = 1;

        /// <summary>
        /// Показывать ли сетку.
        /// 
        /// Включено: между клетками рисуются линии сетки.
        /// Выключено: клетки отображаются без разделителей.
        /// 
        /// Отключение сетки улучшает производительность и уменьшает
        /// визуальный шум при большом зуме.
        /// </summary>
        public bool ShowGrid { get; set; } = false;

        /// <summary>
        /// Отрисовывать ли информацию о поколении.
        /// 
        /// Включено: в углу изображения рисуется текст с номером
        /// поколения и количеством живых клеток.
        /// Выключено: только клетки и сетка.
        /// 
        /// Полезно для скриншотов и отладки, но может мешать
        /// при экспорте чистых изображений.
        /// </summary>
        public bool ShowGenerationInfo { get; set; } = false;

        /// <summary>
        /// Создаёт конфигурацию по умолчанию.
        /// 
        /// Использует сбалансированные настройки для обычного просмотра:
        /// - Средний размер клетки (4 пикселя)
        /// - Контрастные цвета (красный на чёрном)
        /// - Сетка отключена (лучшая производительность)
        /// </summary>
        /// <returns>Новый объект RenderConfig с настройками по умолчанию.</returns>
        public static RenderConfig CreateDefault()
        {
            return new RenderConfig
            {
                CellSize = 4,
                AliveColor = System.Drawing.Color.Crimson,
                DeadColor = System.Drawing.Color.Black,
                GridColor = System.Drawing.Color.DarkGray,
                GridThickness = 1,
                ShowGrid = false,
                ShowGenerationInfo = false
            };
        }

        /// <summary>
        /// Создаёт конфигурацию для экспорта высокого качества.
        /// 
        /// Использует увеличенный размер клетки для детализации.
        /// Подходит для скриншотов и презентаций.
        /// </summary>
        /// <returns>Новый объект RenderConfig для экспорта.</returns>
        public static RenderConfig CreateForExport()
        {
            return new RenderConfig
            {
                CellSize = 8,
                AliveColor = System.Drawing.Color.Crimson,
                DeadColor = System.Drawing.Color.Black,
                GridColor = System.Drawing.Color.DarkGray,
                GridThickness = 1,
                ShowGrid = true,
                ShowGenerationInfo = true
            };
        }

        /// <summary>
        /// Создаёт конфигурацию для headless режима.
        /// 
        /// Минимальный размер клетки для максимальной производительности.
        /// Все декоративные элементы отключены.
        /// </summary>
        /// <returns>Новый объект RenderConfig для headless.</returns>
        public static RenderConfig CreateForHeadless()
        {
            return new RenderConfig
            {
                CellSize = 1,
                AliveColor = System.Drawing.Color.White,
                DeadColor = System.Drawing.Color.Black,
                GridColor = System.Drawing.Color.Black,
                GridThickness = 0,
                ShowGrid = false,
                ShowGenerationInfo = false
            };
        }
    }
}