using System;
using GameOfLife.Core;

namespace GameOfLife.Rendering
{
    /// <summary>
    /// Пустой рендерер (для headless режима).
    /// 
    /// Этот класс реализует интерфейс IRenderer но не выполняет
    /// никакой фактической отрисовки. Все методы пустые.
    /// 
    /// Назначение:
    /// - Запуск симуляции без визуализации (максимальная производительность)
    /// - Паттерн Null Object: избегает проверок на null в коде движка
    /// - Тестирование: позволяет тестировать логику без зависимостей от графики
    /// 
    /// Использование:
    /// var renderer = new NullRenderer();
    /// engine.SetRenderer(renderer);
    /// // Симуляция работает но ничего не рисуется
    /// 
    /// Производительность:
    /// - Время отрисовки: ~0 мс (методы пустые)
    /// - Потребление памяти: минимальное
    /// - Подходит для симуляций на 10000+ поколений
    /// </summary>
    public class NullRenderer : IRenderer
    {
        /// <summary>
        /// Конфигурация рендерера (не используется).
        /// 
        /// Свойство реализовано для совместимости с интерфейсом.
        /// Значение не влияет на поведение этого класса.
        /// </summary>
        public RenderConfig Config { get; set; } = RenderConfig.CreateDefault();

        /// <summary>
        /// Событие завершения отрисовки (не используется).
        /// 
        /// Событие реализовано для совместимости с интерфейсом.
        /// Никогда не вызывается.
        /// </summary>
        public event Action<RenderStats> OnRenderCompleted;

        /// <summary>
        /// Отрисовка не выполняется.
        /// 
        /// Метод пустой — просто возвращает управление.
        /// Это позволяет движку вызывать Render без проверок.
        /// </summary>
        /// <param name="worldState">Игнорируется.</param>
        public void Render(WorldState worldState)
        {
            // Ничего не делаем - headless режим
            // Это намеренно: позволяет избежать проверок на null в движке
        }

        /// <summary>
        /// Сохранение не выполняется.
        /// 
        /// Метод пустой — просто возвращает управление.
        /// </summary>
        /// <param name="filePath">Игнорируется.</param>
        public void SaveFrame(string filePath)
        {
            // Ничего не делаем
        }

        /// <summary>
        /// Запись не выполняется.
        /// 
        /// Метод пустой — просто возвращает управление.
        /// </summary>
        public void BeginRecording()
        {
            // Ничего не делаем
        }

        /// <summary>
        /// Завершение записи не выполняется.
        /// 
        /// Метод пустой — просто возвращает управление.
        /// </summary>
        /// <param name="outputPath">Игнорируется.</param>
        /// <param name="fps">Игнорируется.</param>
        public void EndRecording(string outputPath, int fps)
        {
            // Ничего не делаем
        }

        /// <summary>
        /// Освобождение ресурсов (пустое).
        /// 
        /// Метод реализован для совместимости с IDisposable.
        /// Не требует выполнения никаких действий.
        /// </summary>
        public void Dispose()
        {
            // Ничего не делаем - нет ресурсов для освобождения
        }
    }
}