namespace GameOfLife
{
    /// <summary>
    /// Перечисление состояний движка симуляции.
    /// 
    /// Определяет три основных режима работы игрового движка:
    /// - run: симуляция активна и выполняется
    /// - pause: симуляция приостановлена, состояние сохранено
    /// - stop: симуляция остановлена, возможен сброс параметров
    /// 
    /// Это перечисление используется в GameEngine для контроля
    /// выполнения основного цикла симуляции.
    /// 
    /// Пример использования:
    /// if (_statusEngine == StatusEngine.run) { NextGeneration(); }
    /// 
    /// Примечание:
    /// В новой архитектуре (Core/) это перечисление заменено на
    /// SimulationStatus с более современными соглашениями именования.
    /// </summary>
    public enum StatusEngine
    {
        /// <summary>
        /// Режим выполнения.
        /// 
        /// Симуляция активна, каждый тик таймера вызывает NextGeneration().
        /// Клетки эволюционируют согласно правилам игры.
        /// 
        /// В этом режиме:
        /// - Таймер включён (timer.Enabled = true)
        /// - Кнопка Start отображает текст "Pause"
        /// - Кнопка Stop отображает текст "Stop"
        /// - Изменение плотности (nudDensity) заблокировано
        /// </summary>
        run,

        /// <summary>
        /// Режим паузы.
        /// 
        /// Симуляция приостановлена, текущее состояние мира сохранено.
        /// Пользователь может изучить текущее поколение, изменить камеру,
        /// но клетки не эволюционируют.
        /// 
        /// В этом режиме:
        /// - Таймер выключен (timer.Enabled = false)
        /// - Кнопка Start отображает текст "Resume"
        /// - Кнопка Stop отображает текст "Reset"
        /// - Изменение плотности заблокировано
        /// 
        /// Для возобновления используется ResumeGame().
        /// </summary>
        pause,

        /// <summary>
        /// Режим остановки.
        /// 
        /// Симуляция полностью остановлена. Пользователь может:
        /// - Изменить размер мира
        /// - Изменить плотность случайного заполнения
        /// - Очистить поле и начать заново
        /// 
        /// В этом режиме:
        /// - Таймер выключен (timer.Enabled = false)
        /// - Кнопка Start отображает текст "Start"
        /// - Кнопка Stop отображает текст "Reset"
        /// - Изменение плотности разблокировано
        /// 
        /// Для запуска используется StartGame().
        /// </summary>
        stop
    }
}